import Foundation

/// Maps macOS virtual key codes (kVK_*, physical key positions) to XT "set 1" scancodes, the
/// numbering QEMU's extended RFB key event expects. Extended (E0-prefixed) keys carry bit 0x80.
/// Sending physical keys instead of characters keeps the guest's own keyboard layout in charge.
public enum MacKeyMap {
    public static let extended: UInt32 = 0x80

    /// XT scancode for a macOS key code, or nil when the key has no PC equivalent (e.g. Fn).
    public static func xtCode(forMacKeyCode code: UInt16) -> UInt32? { table[code] }

    // Well-known XT codes used outside this file.
    public static let leftControl: UInt32 = 0x1D
    public static let leftAlt: UInt32 = 0x38
    public static let delete: UInt32 = 0x53 | extended

    private static let table: [UInt16: UInt32] = {
        let e = extended
        return [
            // Letters (kVK_ANSI_*)
            0x00: 0x1E, 0x0B: 0x30, 0x08: 0x2E, 0x02: 0x20, 0x0E: 0x12, 0x03: 0x21, 0x05: 0x22, 0x04: 0x23,
            0x22: 0x17, 0x26: 0x24, 0x28: 0x25, 0x25: 0x26, 0x2E: 0x32, 0x2D: 0x31, 0x1F: 0x18, 0x23: 0x19,
            0x0C: 0x10, 0x0F: 0x13, 0x01: 0x1F, 0x11: 0x14, 0x20: 0x16, 0x09: 0x2F, 0x0D: 0x11, 0x07: 0x2D,
            0x10: 0x15, 0x06: 0x2C,
            // Digits row
            0x12: 0x02, 0x13: 0x03, 0x14: 0x04, 0x15: 0x05, 0x17: 0x06, 0x16: 0x07, 0x1A: 0x08, 0x1C: 0x09,
            0x19: 0x0A, 0x1D: 0x0B,
            // Punctuation
            0x1B: 0x0C, 0x18: 0x0D, 0x21: 0x1A, 0x1E: 0x1B, 0x2A: 0x2B, 0x29: 0x27, 0x27: 0x28, 0x2B: 0x33,
            0x2F: 0x34, 0x2C: 0x35, 0x32: 0x29, 0x0A: 0x56,
            // Editing / whitespace
            0x24: 0x1C, 0x30: 0x0F, 0x31: 0x39, 0x33: 0x0E, 0x35: 0x01, 0x75: 0x53 | e,
            // Modifiers (Command acts as the Windows/Meta key)
            0x38: 0x2A, 0x3C: 0x36, 0x3B: 0x1D, 0x3E: 0x1D | e, 0x3A: 0x38, 0x3D: 0x38 | e,
            0x37: 0x5B | e, 0x36: 0x5C | e, 0x39: 0x3A,
            // Function keys
            0x7A: 0x3B, 0x78: 0x3C, 0x63: 0x3D, 0x76: 0x3E, 0x60: 0x3F, 0x61: 0x40, 0x62: 0x41, 0x64: 0x42,
            0x65: 0x43, 0x6D: 0x44, 0x67: 0x57, 0x6F: 0x58,
            // Navigation
            0x7B: 0x4B | e, 0x7C: 0x4D | e, 0x7D: 0x50 | e, 0x7E: 0x48 | e, 0x73: 0x47 | e, 0x77: 0x4F | e,
            0x74: 0x49 | e, 0x79: 0x51 | e, 0x72: 0x52 | e,
            // Keypad
            0x52: 0x52, 0x53: 0x4F, 0x54: 0x50, 0x55: 0x51, 0x56: 0x4B, 0x57: 0x4C, 0x58: 0x4D, 0x59: 0x47,
            0x5B: 0x48, 0x5C: 0x49, 0x41: 0x53, 0x43: 0x37, 0x45: 0x4E, 0x47: 0x45, 0x4B: 0x35 | e,
            0x4C: 0x1C | e, 0x4E: 0x4A,
        ]
    }()
}
